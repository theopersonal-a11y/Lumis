export const ITEMS = {};
for (const [id, name, icon, rarity, value, desc, extra] of ITEM_LIST) {
  const [tpl, cols] = icon.split(':'); const [a, b, c] = cols.split(',');
  ITEMS[id] = { id, name, rarity, value, desc, tpl, cols: { a: PAL[a], b: PAL[b], c: PAL[c] }, stack: 99, type: 'material', ...(extra || {}) };
  if (extra && (extra.heal || extra.use)) ITEMS[id].type = 'consumable';
  if (extra && extra.food) ITEMS[id].type = 'food';
}
export function itemIcon(id) {
  const it = ITEMS[id]; if (!it) return null;
  if (it.icon) return it.icon;
  const rows = ICON[it.tpl] || ICON.ore;
  const pal = { a: it.cols.a, b: it.cols.b, c: it.cols.c, k: '#10101a', L: PAL.L };
  return it.icon = makeSprite(rows, pal, 'item:' + id);
}
export function registerItem(def) { ITEMS[def.id] = def; return def; }
